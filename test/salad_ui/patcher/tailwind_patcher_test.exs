defmodule SaladUI.Patcher.TailwindPatcherTest do
  use ExUnit.Case

  alias SaladUI.Patcher.TailwindPatcher

  @temp_dir "test/temp"
  @tailwind_css "#{@temp_dir}/app.css"

  setup do
    File.mkdir_p!(@temp_dir)
    on_exit(fn -> File.rm_rf!(@temp_dir) end)
  end

  describe "Test Tailwind CSS entrypoint patcher" do
    test "patch/1 adds v4 import, sources, plugins, and theme when missing" do
      File.write!(@tailwind_css, "")

      TailwindPatcher.patch(@tailwind_css)

      patched_content = File.read!(@tailwind_css)
      assert patched_content =~ ~s(@import "tailwindcss";)

      assert patched_content =~
               ~s{@custom-variant dark (&:where(.dark, .dark *, [data-theme=dark], [data-theme=dark] *));}

      assert patched_content =~ ~s(@source "../js";)
      assert patched_content =~ ~s(@source "../../lib";)
      assert patched_content =~ ~s(@source "../../deps/salad_ui/lib";)
      assert patched_content =~ ~s(@source "../../deps/salad_ui/assets/salad_ui";)
      assert patched_content =~ ~s(@source not "../../deps/salad_ui/assets/salad_ui/components/emoji_picker";)
      assert patched_content =~ ~s(@source not "../js/ui/components/emoji_picker";)
      assert patched_content =~ ~s(@plugin "@tailwindcss/typography";)
      assert patched_content =~ ~s(@import "../vendor/tw-animate.css";)
      assert patched_content =~ "@theme inline {"
      assert patched_content =~ "--color-background: var(--background);"
      assert patched_content =~ "--radius-lg: var(--radius);"
    end

    test "patch/1 doesn't duplicate existing directives" do
      initial_content = """
      @import "tailwindcss";
      @custom-variant dark (&:where(.dark, .dark *));
      @source "../js";
      @source "../../lib";
      @source "../../deps/salad_ui/lib";
      @plugin "@tailwindcss/typography";
      @import "../vendor/tw-animate.css";
      @theme {
        --color-background: hsl(var(--background));
      }
      """

      File.write!(@tailwind_css, initial_content)

      TailwindPatcher.patch(@tailwind_css)

      patched_content = File.read!(@tailwind_css)

      assert count(patched_content, ~s(@import "tailwindcss";)) == 1
      assert count(patched_content, "@custom-variant dark") == 1
      assert count(patched_content, ~s(@source "../js";)) == 1
      assert count(patched_content, ~s(@source "../../lib";)) == 1
      assert count(patched_content, ~s(@source "../../deps/salad_ui/lib";)) == 1
      assert count(patched_content, ~s(@source "../../deps/salad_ui/assets/salad_ui";)) == 1
      assert count(patched_content, ~s(@plugin "@tailwindcss/typography";)) == 1
      assert count(patched_content, ~s(@import "../vendor/tw-animate.css";)) == 1
      assert count(patched_content, "--color-background:") == 1
    end

    test "patch/1 replaces v3 Tailwind imports" do
      initial_content = """
      @import "tailwindcss/base";
      @import "tailwindcss/components";
      @import "tailwindcss/utilities";
      """

      File.write!(@tailwind_css, initial_content)

      TailwindPatcher.patch(@tailwind_css)

      patched_content = File.read!(@tailwind_css)

      assert patched_content =~ ~s(@import "tailwindcss";)
      refute patched_content =~ "tailwindcss/base"
      refute patched_content =~ "tailwindcss/components"
      refute patched_content =~ "tailwindcss/utilities"
    end
  end

  describe "Phoenix 1.8 app.css" do
    # Directives as generated by phx.new 1.8 (installer/templates/phx_assets/app.css)
    @phoenix_1_8_css """
    @import "tailwindcss" source(none);
    @source "../css";
    @source "../js";
    @source "../../lib/my_app_web";

    @plugin "../vendor/heroicons";

    @custom-variant phx-click-loading (.phx-click-loading&, .phx-click-loading &);

    /* Use the data attribute for dark mode  */
    @custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));
    """

    test "keeps the single source(none) tailwind import" do
      File.write!(@tailwind_css, @phoenix_1_8_css)
      TailwindPatcher.patch(@tailwind_css)
      patched = File.read!(@tailwind_css)

      assert count(patched, "@import \"tailwindcss\"") == 1
      assert patched =~ ~s{@import "tailwindcss" source(none);}
    end

    test "replaces the data-theme-only dark variant instead of adding a second one" do
      File.write!(@tailwind_css, @phoenix_1_8_css)
      TailwindPatcher.patch(@tailwind_css)
      patched = File.read!(@tailwind_css)

      assert count(patched, "@custom-variant dark ") == 1
      assert patched =~ "[data-theme=dark]"
      assert patched =~ ".dark, .dark *"
      assert patched =~ "@custom-variant phx-click-loading"
    end

    test "is idempotent" do
      File.write!(@tailwind_css, @phoenix_1_8_css)
      TailwindPatcher.patch(@tailwind_css)
      once = File.read!(@tailwind_css)
      TailwindPatcher.patch(@tailwind_css)

      assert File.read!(@tailwind_css) == once
    end
  end

  describe "theme tokens" do
    # `--x: value;` declarations inside an `@theme inline { ... }` block.
    defp theme_decls(css) do
      [_, block] = Regex.run(~r/@theme inline \{(.*?)\n\s*\}/s, css)

      ~r/(--[\w-]+):\s*([^;]+);/
      |> Regex.scan(block)
      |> Map.new(fn [_, name, value] -> {name, value} end)
    end

    defp patched_theme do
      File.write!(@tailwind_css, "")
      TailwindPatcher.patch(@tailwind_css)
      theme_decls(File.read!(@tailwind_css))
    end

    test "installer theme block matches assets/css/tailwind.theme.css" do
      assert patched_theme() == theme_decls(File.read!("assets/css/tailwind.theme.css"))
    end

    test "maps shadcn's sidebar, chart and radius tokens" do
      theme = patched_theme()

      assert theme["--color-sidebar"] == "var(--sidebar, var(--sidebar-background))"

      for i <- 1..5 do
        assert theme["--color-chart-#{i}"] == "var(--chart-#{i})"
      end

      for size <- ~w(sm md lg xl 2xl 3xl 4xl) do
        assert Map.has_key?(theme, "--radius-#{size}")
      end
    end

    test "every color scheme defines each token the theme reads" do
      read =
        patched_theme()
        |> Map.values()
        |> Enum.flat_map(&Regex.scan(~r/var\((--[\w-]+)/, &1, capture: :all_but_first))
        |> List.flatten()
        |> Enum.uniq()
        # back-compat fallback name; schemes define `--sidebar`
        |> List.delete("--sidebar-background")

      for path <- Path.wildcard("priv/static/assets/colors/*.css") do
        css = File.read!(path)
        refute css =~ "--sidebar-background:", "#{path} should use shadcn's --sidebar name"

        for token <- read do
          assert css =~ "#{token}:", "#{path} is missing #{token}"
        end
      end
    end

    test "patch/1 upgrades a theme block that reads only --sidebar-background" do
      File.write!(@tailwind_css, """
      @import "tailwindcss";
      @theme inline {
        --color-background: var(--background);
        --color-sidebar: var(--sidebar-background);
      }
      """)

      TailwindPatcher.patch(@tailwind_css)
      patched = File.read!(@tailwind_css)

      assert patched =~ "--color-sidebar: var(--sidebar, var(--sidebar-background));"
      assert count(patched, "--color-sidebar:") == 1
    end
  end

  describe "patch_color_scheme/2" do
    @scheme_css File.read!("priv/static/assets/colors/gray.css")

    test "injects tokens, dark selectors for .dark and data-theme, and border defaults" do
      File.write!(@tailwind_css, ~s(@import "tailwindcss";\n))
      TailwindPatcher.patch_color_scheme(@tailwind_css, @scheme_css)
      patched = File.read!(@tailwind_css)

      assert patched =~ "@layer base {"
      assert patched =~ "--border: oklch("
      assert patched =~ ~s(.dark,\n[data-theme="dark"] {)
      assert patched =~ "@apply border-border outline-ring/50;"
      # tokens are oklch; wrapping them in hsl() is invalid CSS
      refute patched =~ "hsl(var("
    end

    test "is idempotent" do
      File.write!(@tailwind_css, ~s(@import "tailwindcss";\n))
      TailwindPatcher.patch_color_scheme(@tailwind_css, @scheme_css)
      once = File.read!(@tailwind_css)
      TailwindPatcher.patch_color_scheme(@tailwind_css, @scheme_css)

      assert File.read!(@tailwind_css) == once
    end
  end

  defp count(content, pattern) do
    content |> String.split(pattern) |> length() |> Kernel.-(1)
  end
end
